export function getPersonalizedSpokenSummary(profile: UserProfile, lang: LanguageCode): string {
  const name = profile.name ? profile.name.trim().split(' ')[0] : 'Beneficiary';
  const occupation = profile.currentOccupation || 'practical skills';
  const interests = (profile.interests && profile.interests.length > 0)
    ? profile.interests.slice(0, 2).join(' and ')
    : 'technical vocations';
  const pref = profile.employmentPreference === 'Self-employment'
    ? 'self-employment'
    : profile.employmentPreference === 'Employment'
    ? 'employment'
    : 'career opportunities';

  switch (lang) {
    case 'te':
      return `ధన్యవాదాలు ${name}. మీ ${occupation} అనుభవం, ${interests} పై ఆసక్తి మరియు ${pref} ప్రాధాన్యత ఆధారంగా, నేను మీ కోసం తగిన NSQF జీవనోపాధి మార్గాలను సిద్ధం చేశాను.`;
    case 'hi':
      return `धन्यवाद ${name}। आपके ${occupation} अनुभव, ${interests} में आपकी रुचि और ${pref} की प्राथमिकता के आधार पर, मैंने आपके लिए उपयुक्त NSQF आजीविका मार्ग तैयार किए हैं।`;
    case 'mr':
      return `धन्यवाद ${name}. तुमचा ${occupation} कामाचा अनुभव, ${interests} मधील तुमची आवड आणि ${pref} यावर आधारित, मी तुमच्यासाठी योग्य NSQF उपजीविका मार्ग शोधले आहेत.`;
    case 'ur':
      return `شکریہ ${name}۔ آپ کے ${occupation} کے تجربے، ${interests} میں آپ کی دلچسپی اور ${pref} کی ترجیح پر، میں نے آپ کے لیے موزوں روزگار کے راستے تیار کیے ہیں۔`;
    case 'ta':
      return `நன்றி ${name}. உங்கள் ${occupation} அனுபவம், ${interests} மீதான ஆர்வம் மற்றும் ${pref} விருப்பத்தின் அடிப்படையில், உங்களுக்கான சிறந்த NSQF வாழ்வாதார வழிகளை நான் தயார் செய்துள்ளேன்.`;
    case 'en':
    default:
      return `Thank you ${name}. Based on your ${occupation} experience, interest in ${interests} and preference for ${pref}, I found tailored NSQF livelihood pathways for you.`;
  }
}

